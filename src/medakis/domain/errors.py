"""Alan hataları: kodlu, Türkçe ve parametre değeri içermeyen mesajlar."""

from __future__ import annotations


class DomainError(ValueError):
    """İş kuralı ihlali. `code` makine tarafından, `message` kullanıcı tarafından okunur."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message


